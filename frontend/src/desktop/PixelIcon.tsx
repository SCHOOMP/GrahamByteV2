function toPath(map: string[], char: string): string {
  let d = '';
  map.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === char) d += `M${x} ${y}h1v1h-1z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(
  Object.entries(MAPS).map(([name, map]) => [name, { full: toPath(map, '#'), dim: toPath(map, '+') }]),
) as Record<PixelIconName, { full: string; dim: string }>;

export function PixelIcon({ name }: { name: PixelIconName }) {
  const { full, dim } = PATHS[name];
  return (
    <svg className="pixel-icon" viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true">
      <path d={dim} fill="currentColor" opacity={0.4} />
      <path d={full} fill="currentColor" />
    </svg>
  );
}
